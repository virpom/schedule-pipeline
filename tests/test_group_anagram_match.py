"""Анаграмма группы — не «точное совпадение» (план 119).

match_group отдавал score=1.0 всякому кандидату с тем же набором
символов. «ПД-26» и «ДП-26» — анаграмма, но это разные специальности;
уверенное совпадение тут хуже, чем «не нашли».

Теперь при том же наборе символов решают цифры: «26ДП» и «ДП26» —
перепутанный порядок одной группы (номер тот же), а «ПД26» и «ДП26» —
разные группы при тех же цифрах.

На проде 130 групп, анаграммных пар 0, так что регресса быть не
должно — проверено.
"""
from parsers.eios import match_group


def test_reordered_same_group_found():
    """«26ДП» -> «ДП-26»: буквы и цифры поменялись местами."""
    assert match_group("26ДП", ["ДП-26"]) == "ДП-26"


def test_different_specialty_not_matched():
    """«ПД-26» не должно склеиваться с «ДП-26» — это разные специальности.

    Старый код отдавал ДП-26 уверенно: анаграмма плюс номер совпал.
    Теперь цифры одинаковы у обеих, буквы разные — 0.0, кандидата нет.
    """
    assert match_group("ПД-26", ["ДП-26", "ИС-25"]) is None, \
        "анаграмма другой специальности принята за точное совпадение"


def test_ambiguous_anagram_not_guessed():
    """Обе группы анаграммны и обе с номером 26 — не угадываем."""
    assert match_group("26ДП", ["ДП-26", "ПД-26"]) is None


def test_typo_table_still_wins():
    """Таблица опечаток работает до похожести."""
    assert match_group("ДП26", ["ДП-26"]) == "ДП-26"


def test_substring_match_kept():
    assert match_group("ИС-25-2", ["ИС-25"]) == "ИС-25"
