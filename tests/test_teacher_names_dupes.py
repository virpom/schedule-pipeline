"""Один преподаватель — одна строка в списке (планы 149 и 172).

Расписание одного человека записано по-разному, и distinct() по сырой
строке возвращал обоих. Замерено на проде: колледж — 187 имён, 12
групп дублей; вуз — 137 имён, 16 групп. Человек видел два одинаковых
пункта и не знал, какой верный.

Канон остаётся прежним — с точкой после инициалов («Кулян Р.А.»):
чистка живёт в ключе сравнения, а не в teacher_base. Попытка менять
teacher_base сломала 13 тестов, потому что от канона зависит поиск.
"""
from infrastructure.database.repo.college_lesson import _clean_teacher_names as clean


def test_trailing_dot_merged():
    assert clean(["Воробьев М.С", "Воробьев М.С."]) == ["Воробьев М.С."]


def test_dot_form_preferred():
    """Показываем вариант с точкой, даже если он в списке первым."""
    assert clean(["Кулян Р.А.", "Кулян Р.А"]) == ["Кулян Р.А."]
    assert clean(["Кулян Р.А", "Кулян Р.А."]) == ["Кулян Р.А."]


def test_missing_space_merged():
    """«ВостриковК.В.» — та же строка без пробела; канон с пробелом."""
    assert clean(["Востриков К.В.", "ВостриковК.В."]) == ["Востриков К.В."]


def test_dot_after_surname_merged():
    assert clean(["Каверзин А.В.", "Каверзин. А.В."]) == ["Каверзин А.В."]


def test_vacancy_still_filtered():
    assert clean(["Вакансия", "вакансия"]) == []


def test_different_people_kept():
    got = clean(["Иванов И.И.", "Иванов П.П.", "Петров И.И."])
    assert got == ["Иванов И.И.", "Иванов П.П.", "Петров И.И."], got


def test_surname_only_dropped_if_full_exists():
    assert clean(["Ляшко", "Ляшко Д.В."]) == ["Ляшко Д.В."]


def test_comma_splits_people():
    """«Багомедова У.М., Левочкина Н.А.» — двое, а не один."""
    got = clean(["Багомедова У.М., Левочкина Н.А."])
    assert got == ["Багомедова У.М.", "Левочкина Н.А."], got
